from enum import Enum


class IntegrationStatus(str, Enum):
    SUCCESS = "SUCCESS"
    FAILED = "FAILED"
    SKIPPED = "SKIPPED"
    PARTIALLY_SUCCESS = "PARTIALLY_SUCCESS"


class IntegrationAction(str, Enum):
    CREATE = "CREATE"
    UPDATE = "UPDATE"
    RETRY_CREATE = "RETRY_CREATE"


class ProcessingStage(str, Enum):
    REPORT_FETCH = "REPORT_FETCH"
    EXPENSE_SHEET_CREATION = "EXPENSE_SHEET_CREATION"
    EXPENSE_LINE_CREATION = "EXPENSE_LINE_CREATION"
    SUBMISSION = "SUBMISSION"
    APPROVAL = "APPROVAL"
    COMPLETED = "COMPLETED"
